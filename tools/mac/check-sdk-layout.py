#!/usr/bin/env python3
"""check-sdk-layout.py: compile-time layout check of the WHOLE RED4ext SDK against the Mac game's reflection dump.

For every generated SDK header whose class the dump knows, it emits `static_assert(offsetof(T, member) == <dump offset>)` for each member the SDK
declares by name (a trailing underscore on a reserved word is ignored), puts them all in one translation unit and compiles it with clang
(-fsyntax-only, as the Apple side of the headers sees it). The per-plugin guard (MacLayoutGuard.cpp, generated by gen-mac-layout.py --guard) checks
only the classes one plugin sees; this check covers every class the SDK declares, so a plugin nobody has checked yet starts from a correct layout.

Gate result:
  LAYOUT failures        a member sits at another offset than in the game              -> fails the check
  negative padding       an Apple padding array has a negative size ("array is too large") -> fails the check
  other compile errors   headers that do not compile for reasons unrelated to the layout (an undeclared type, an abstract class);
                         reported with a count, not gated (the SDK carries a few from the Windows generator)

Usage: check-sdk-layout.py --dump layout/reflection-2026-10-08.tsv [--sdk <RED4ext.SDK-macos>/include] [--work DIR] [--keep]
Idea of a whole-SDK offset check: jackmaxwil/RED4ext.SDK-macos scripts/gen_macos_layouts.py (--verify compiles every header), MIT. This script is
an independent implementation that reads the dump of this tree.
"""
import argparse, collections, os, re, subprocess, sys, tempfile

APPLE = re.compile(r'^#\s*if(?:def)?\s+(?:defined\()?\s*__APPLE__\)?[^\n]*\n(.*?)^#\s*else[^\n]*\n.*?^#\s*endif[^\n]*\n', re.S | re.M)
NAME = re.compile(r'static constexpr const char\* NAME = "([^"]+)";')
STRUCT = re.compile(r'^struct (?:__declspec\(align\(0x[0-9A-Fa-f]+\)\) )?(\w+)(?:\s*:\s*[\w:<>, ]+)?\s*$', re.M)
NS = re.compile(r'^namespace ([\w:]+)\s*$', re.M)
FIELD = re.compile(r'^\s+(?:alignas\(\d+\) )?[\w:<>,\s\*&]+?\s+(\w+)(?:\[[^\]]*\])?(?:\s+__attribute__\(\(packed\)\))?;[ \t]*(?://[ \t]*([0-9A-Fa-f]+))?', re.M)


def load_dump(path):
    mac = {}
    for line in open(path):
        p = line.rstrip('\n').split('\t')
        if p[0] == 'P':
            mac[(p[1], p[2])] = int(p[3])
    return mac


def build_tu(sdk_include, mac):
    gen = os.path.join(sdk_include, 'RED4ext/Scripting/Natives/Generated')
    headers, lines = [], []
    for root, _, files in os.walk(gen):
        for f in sorted(files):
            if not f.endswith('.hpp'):
                continue
            path = os.path.join(root, f)
            text = open(path, errors='ignore').read()
            if '\n/*\n' in text:
                continue                       # redirect to a hand-written class
            n = NAME.search(text)
            if not n:
                continue
            rtti = n.group(1)
            t2 = APPLE.sub(lambda m: m.group(1), text)
            s = STRUCT.search(t2)
            if not s:
                continue
            ns = [m.group(1) for m in NS.finditer(t2) if m.start() < s.start()]
            prefix = ns[-1] if ns and ns[-1] != 'RED4ext' else ''
            cpp = (prefix + '::' if prefix else '') + s.group(1)
            end = t2.find('RED4EXT_ASSERT_SIZE', s.end())
            body = t2[s.end(): end if end >= 0 else len(t2)]
            members = []
            for m in FIELD.finditer(body):
                nm = m.group(1)
                if nm.startswith('unk') or nm in ('NAME', 'ALIAS'):
                    continue
                key = nm if (rtti, nm) in mac else (nm[:-1] if nm.endswith('_') and (rtti, nm[:-1]) in mac else None)
                if key is not None:
                    members.append((nm, mac[(rtti, key)]))
            if not members:
                continue
            headers.append(os.path.relpath(path, sdk_include))
            for nm, off in members:
                lines.append('static_assert(offsetof(RED4ext::%s, %s) == %d, "LAYOUT %s %s %d");' % (cpp, nm, off, rtti, nm, off))
    tu = '#include <RED4ext/RED4ext.hpp>\n#include <cstddef>\n' + ''.join('#include <%s>\n' % h for h in headers) + '\n'.join(lines) + '\n'
    return tu, len(headers), len(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dump', required=True)
    ap.add_argument('--sdk', default=os.path.expanduser('~/repos/cp2077-mac/RED4ext.SDK-macos/include'))
    ap.add_argument('--work', default=None)
    ap.add_argument('--keep', action='store_true')
    a = ap.parse_args()
    mac = load_dump(a.dump)
    tu, nclasses, nmembers = build_tu(a.sdk, mac)
    work = a.work or tempfile.mkdtemp(prefix='sdk-layout-')
    os.makedirs(work, exist_ok=True)
    cpp = os.path.join(work, 'sdk-layout-check.cpp')
    open(cpp, 'w').write(tu)
    print('check-sdk-layout: %d classes, %d member offsets, translation unit %s' % (nclasses, nmembers, cpp))
    cmd = ['xcrun', 'clang++', '-std=c++20', '-fsyntax-only', '-ferror-limit=0', '-w', '-Wno-invalid-offsetof', '-I', a.sdk, cpp]
    p = subprocess.run(cmd, capture_output=True, text=True)
    log = p.stderr
    open(os.path.join(work, 'sdk-layout-check.log'), 'w').write(log)
    layout = sorted(set(re.findall(r'static assertion failed due to requirement[^\n]*LAYOUT (\S+ \S+ \d+)', log)))
    negative = sorted(set(re.sub(r'.*Generated/', '', h) for h in re.findall(r'(\S*Generated/\S*\.hpp):\d+:\d+: error: array is too large', log)))
    other = collections.Counter(re.sub(r'\s+', ' ', m) for m in re.findall(r'error: ([a-zA-Z ]+?)(?: \'|:|$)', log, re.M)
                                if not m.startswith(('static assertion', 'array is too large')))
    nother = sum(other.values())
    unchecked = len(re.findall(r'static assertion expression is not an integral constant expression', log))
    print('LAYOUT failures: %d' % len(layout))
    for l in layout:
        print('   ', l)
    print('negative padding headers: %d' % len(negative))
    for h in negative:
        print('   ', h)
    print('other compile errors (not gated, unrelated to the layout): %d; members left unchecked because of them: %d' % (nother, unchecked))
    if not a.keep and not a.work:
        pass
    ok = not layout and not negative
    print('check-sdk-layout: %s' % ('PASS' if ok else 'FAIL'))
    return 0 if ok else 1


sys.exit(main())
