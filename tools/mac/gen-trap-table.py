#!/usr/bin/env python3
"""Generate macos/MacTrapTable.inc, the compile-time list of address hashes that get a trap stub on macOS.

Inputs (plain text, no build needed):
  src/Red/Addresses/Library.hpp                 Codeware's own address hashes   (constexpr uint32_t Name = N;)
  <sdk>/RED4ext/Detail/AddressHashes.hpp        the RED4ext SDK hashes          (constexpr std::uint32_t Name = 0x..)
Each hash becomes one line, by how the sources use it (see addrscan.py):
  TRAP_FUNC(h, "Name")   function; the trap returns 0 in x0 and x1
  TRAP_FLT(h, "Name")    function declared to return float or double; the trap also zeroes v0
  TRAP_DATA(h, "Name")   read as data (RawPtr, RawOffset, UniversalRelocPtr, UniversalRelocVtbl); the trap is a zeroed buffer
A hash that nothing uses (declared in the address list only) is TRAP_FUNC.

Usage: gen-trap-table.py [--sdk <path to RED4ext.SDK include dir>] [--out macos/MacTrapTable.inc]
"""
import argparse
import os

import addrscan as A

DATA_KINDS = ('RawPtr', 'RawOffset', 'UniversalRelocPtr', 'UniversalRelocVtbl')
FLOAT_TYPES = ('float', 'double')


def classify(uses):
    """'data', 'float' or 'func' for the uses of one name."""
    if any(u['kind'] in DATA_KINDS for u in uses):
        return 'data'
    if any(u['ret'] in FLOAT_TYPES for u in uses):
        return 'float'
    return 'func'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--sdk', default=A.DEFAULT_SDK)
    ap.add_argument('--out', default=os.path.join(A.ROOT, 'macos', 'MacTrapTable.inc'))
    a = ap.parse_args()

    cw = A.parse_cw(os.path.join(A.ROOT, 'src', 'Red', 'Addresses', 'Library.hpp'))
    sdk = A.parse_sdk(os.path.join(a.sdk, 'RED4ext', 'Detail', 'AddressHashes.hpp'))
    ucw = A.scan_codeware(os.path.join(A.ROOT, 'src'))
    usdk = A.scan_sdk(a.sdk)
    usdk_cw = A.scan_codeware_sdk_names(os.path.join(A.ROOT, 'src'))

    rows = {}  # hash -> [name, kind]
    rank = {'func': 0, 'float': 1, 'data': 2}

    def add(name, h, kind):
        if h in rows:
            if name not in rows[h][0].split('/'):
                rows[h][0] += '/' + name
            if rank[kind] > rank[rows[h][1]]:
                rows[h][1] = kind
        else:
            rows[h] = [name, kind]

    for n, h in sorted(cw.items()):
        add(n, h, classify(ucw.get(n, [])))
    for n, h in sorted(sdk.items()):
        add(n, h, classify(usdk.get(n, []) + usdk_cw.get(n, [])))

    macro = {'func': 'TRAP_FUNC', 'float': 'TRAP_FLT', 'data': 'TRAP_DATA'}
    lines = [
        '// GENERATED by tools/mac/gen-trap-table.py. Do not edit.',
        '// Every address hash the Codeware sources and the RED4ext SDK use, one trap stub each (see MacTrap.cpp).',
        '// %d hashes (%d Codeware, %d SDK, overlap merged).' % (len(rows), len(cw), len(sdk)),
    ]
    for h in sorted(rows):
        n, k = rows[h]
        lines.append('%s(%du, "%s")' % (macro[k], h, n))
    with open(a.out, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    cnt = {k: sum(1 for r in rows.values() if r[1] == k) for k in macro}
    print('wrote %s: %d rows (%d func, %d float, %d data)' % (a.out, len(rows), cnt['func'], cnt['float'], cnt['data']))


if __name__ == '__main__':
    main()
