#!/usr/bin/env python3
"""Generate macos/MacHookStubs.inc: the list of CHAIN_STUB(n) lines for the hook chain (MacHookChain.cpp)."""
import os, sys
N = int(sys.argv[1]) if len(sys.argv) > 1 else 192
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'macos', 'MacHookStubs.inc')
lines = ['// GENERATED by tools/mac/gen-hook-stubs.py. Do not edit.',
         '// %d forwarding stubs for the hook chain (MacHookChain.cpp): each tail-jumps to the function pointer in its slot.' % N]
lines += ['CHAIN_STUB(%d)' % i for i in range(N)]
open(out, 'w').write('\n'.join(lines) + '\n')
print('wrote %s: %d stubs' % (out, N))
